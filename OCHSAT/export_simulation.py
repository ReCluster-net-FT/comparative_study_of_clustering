"""
export_simulation.py
====================

Exports the current network so NS-3 can reproduce it.

The exported JSON contains:

1. Base station position
2. Every sensor node
3. Cluster membership
4. Selected Cluster Heads

All NumPy datatypes are converted to native Python
types so the JSON module can serialize them.
"""

import json
import numpy as np


# ----------------------------------------------------------
# Convert NumPy types to Python types
# ----------------------------------------------------------
def convert(obj):
    """
    Converts NumPy integers/floats to
    standard Python types for JSON.
    """

    if isinstance(obj, np.integer):
        return int(obj)

    if isinstance(obj, np.floating):
        return float(obj)

    if isinstance(obj, np.ndarray):
        return obj.tolist()

    raise TypeError(
        f"{type(obj)} is not JSON serializable"
    )


# ----------------------------------------------------------
# Export network
# ----------------------------------------------------------
def export_network(sim, filename="network.json"):
    """
    Export the complete network generated by the simulator.

    Parameters
    ----------
    sim : Simulator
        Finished simulation object.

    filename : str
        Output JSON filename.
    """

    data = {

        "base_station": {

            "x": float(sim.network.base_station.position[0]),
            "y": float(sim.network.base_station.position[1])

        },

        "nodes": [],

        "cluster_heads": []

    }

    # ------------------------------------------------------
    # Export every sensor node
    # ------------------------------------------------------
    for node in sim.network.nodes:

        data["nodes"].append({

            "id": int(node.node_id),

            "x": float(node.x),

            "y": float(node.y),

            "cluster": int(node.cluster_id),

            "energy": float(node.energy),

            "alive": bool(node.alive)

        })

    # ------------------------------------------------------
    # Export selected Cluster Heads
    # ------------------------------------------------------
    for cid, ch in sim.cluster_heads.items():

        data["cluster_heads"].append({

            "cluster": int(cid),

            "node": int(ch.node_id)

        })

    # ------------------------------------------------------
    # Write JSON file
    # ------------------------------------------------------
    with open(filename, "w") as f:

        json.dump(
            data,
            f,
            indent=4,
            default=convert
        )

    print(f"\nNetwork exported successfully -> {filename}")
